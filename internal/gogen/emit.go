// Package gogen compiles the admitted pilot IR into a standalone Go package.
package gogen

import (
	"bytes"
	"crypto/sha256"
	"embed"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"go/format"
	"go/parser"
	"go/token"
	"sort"
	"strings"

	"github.com/franchb/lean-go/internal/ir"
)

//go:embed templates/runtime.go.tmpl
var templates embed.FS

const Version = "lean-go-gogen/v1"

var functionNames = map[string]string{"LeanGo.Feasibility.normalize": "fnNormalize", "LeanGo.Feasibility.normalizeAux": "fnNormalizeAux", "LeanGo.Feasibility.Tri.neg": "fnTriNeg"}

func goType(t string) string {
	return map[string]string{"bool": "bool", "tri": "Tri", "expr": "*node", "u32": "uint32"}[t]
}
func slot(id int) string { return fmt.Sprintf("v%d", id) }
func zero(t string) string {
	return map[string]string{"bool": "false", "tri": "0", "expr": "nil", "u32": "0"}[t]
}
func digest(data []byte) string { sum := sha256.Sum256(data); return hex.EncodeToString(sum[:]) }

// Generate validates before emission and returns the entire package in memory.
// It validates supplied IR metadata, not the current producer source files.
func Generate(p *ir.Program) (map[string][]byte, error) {
	if err := ir.Validate(p); err != nil {
		return nil, fmt.Errorf("validate IR: %w", err)
	}
	runtime, err := templates.ReadFile("templates/runtime.go.tmpl")
	if err != nil {
		return nil, err
	}
	var code bytes.Buffer
	code.WriteString("// Code generated by lean-go; DO NOT EDIT.\npackage normalizer\n")
	for _, f := range p.Functions {
		e := emitter{program: p, fn: f, states: map[*ir.Code]int{}, resumes: map[*ir.Code]int{}, locals: map[int]string{}}
		e.emit(&code)
	}
	files := map[string][]byte{"runtime.go": runtime, "control.go": code.Bytes()}
	for name, data := range files {
		formatted, err := format.Source(data)
		if err != nil {
			return nil, fmt.Errorf("format %s: %w", name, err)
		}
		if _, err = parser.ParseFile(token.NewFileSet(), name, formatted, parser.AllErrors); err != nil {
			return nil, fmt.Errorf("parse %s: %w", name, err)
		}
		files[name] = formatted
	}
	canonical, err := json.Marshal(p)
	if err != nil {
		return nil, err
	}
	type claim struct {
		ir.Claim
		StatementSHA256 string `json:"statement_sha256"`
	}
	claims := make([]claim, len(p.Claims))
	for i, c := range p.Claims {
		claims[i] = claim{c, digest([]byte(c.Statement))}
	}
	hashes := map[string]string{}
	for name, data := range files {
		hashes[name] = digest(data)
	}
	constructorMappings := map[string]string{}
	for _, typ := range p.Types {
		for _, ctor := range typ.Constructors {
			value := emitter{program: p}
			constructorMappings[ctor.Name] = value.caseValue(typ.Name, ctor.Name)
		}
	}
	manifest := struct {
		Schema          string            `json:"schema"`
		Generator       string            `json:"generator"`
		GeneratorSource string            `json:"generator_source_sha256"`
		ValidatorSource string            `json:"validator_source_sha256"`
		IR              string            `json:"ir_sha256"`
		IRSchema        string            `json:"ir_schema"`
		Profile         string            `json:"profile"`
		Stage           string            `json:"stage"`
		LeanVersion     string            `json:"lean_version"`
		LeanCommit      string            `json:"lean_commit"`
		Model           string            `json:"model_sha256"`
		Root            string            `json:"root"`
		Inputs          map[string]string `json:"inputs"`
		Types           []ir.TypeDecl     `json:"types"`
		Claims          []claim           `json:"claims"`
		Rewrites        []ir.Rewrite      `json:"rewrites"`
		Mappings        map[string]string `json:"function_mappings"`
		Constructors    map[string]string `json:"constructor_mappings"`
		Files           map[string]string `json:"generated_files"`
		Targets         []string          `json:"intended_targets"`
		Evidence        string            `json:"target_evidence"`
	}{"lean-go-manifest/v1", Version, SourceDigest(), ir.SourceDigest(), digest(canonical), p.Schema, p.Profile, p.Stage, p.LeanVersion, p.LeanCommit, p.ModelSHA256, p.Root, p.Inputs, p.Types, claims, p.Rewrites, functionNames, constructorMappings, hashes, []string{"linux/amd64", "windows/amd64"}, "Intended build targets only; this manifest does not certify execution or correctness."}
	data, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return nil, err
	}
	files["manifest.json"] = append(data, '\n')
	return files, nil
}

type emitter struct {
	program         *ir.Program
	fn              ir.Function
	states, resumes map[*ir.Code]int
	nodes           []*ir.Code
	locals          map[int]string
	next            int
}

func (e *emitter) collect(c *ir.Code) {
	e.states[c] = e.next
	e.next++
	e.nodes = append(e.nodes, c)
	if c.Op == "let" {
		e.locals[c.Bind.ID] = c.Bind.Type
		if c.Value.Kind == "call" && c.Value.Name == e.fn.Name {
			e.resumes[c] = e.next
			e.next++
		}
		e.collect(c.Next)
	}
	if c.Op == "cases" {
		for _, a := range c.Alts {
			for _, p := range a.Params {
				e.locals[p.ID] = p.Type
			}
			e.collect(a.Body)
		}
	}
}
func (e *emitter) emit(w *bytes.Buffer) {
	for _, p := range e.fn.Params {
		e.locals[p.ID] = p.Type
	}
	e.collect(e.fn.Body)
	name := functionNames[e.fn.Name]
	frame := name + "Frame"
	result := goType(e.fn.Result)
	fmt.Fprintf(w, "\ntype %s struct { pc int\n", frame)
	ids := make([]int, 0, len(e.locals))
	for id := range e.locals {
		ids = append(ids, id)
	}
	sort.Ints(ids)
	for _, id := range ids {
		fmt.Fprintf(w, "%s %s\n", slot(id), goType(e.locals[id]))
	}
	w.WriteString("}\n")
	fmt.Fprintf(w, "func %s(b *budget", name)
	for _, p := range e.fn.Params {
		fmt.Fprintf(w, ", a%d %s", p.ID, goType(p.Type))
	}
	fmt.Fprintf(w, ") (%s,error) {\n", result)
	recursive := len(e.resumes) > 0
	if recursive {
		fmt.Fprintf(w, "if err:=b.frame(0); err!=nil { return %s,err }; stack:=[]%s{{pc:%d", zero(e.fn.Result), frame, e.states[e.fn.Body])
	} else {
		fmt.Fprintf(w, "if err:=b.frame(0); err!=nil { return %s,err }; defer b.unframe(); f:=&%s{pc:%d", zero(e.fn.Result), frame, e.states[e.fn.Body])
	}
	for _, p := range e.fn.Params {
		fmt.Fprintf(w, ", %s:a%d", slot(p.ID), p.ID)
	}
	if recursive {
		fmt.Fprintf(w, "}}\ndefer func(){ b.frames-=uint64(len(stack)) }()\nvar returned %s\n", result)
	} else {
		w.WriteString("}\n")
	}
	w.WriteString("for {\n")
	if recursive {
		w.WriteString("f:=&stack[len(stack)-1]\n")
	}
	fmt.Fprintf(w, "if err:=b.step(); err!=nil { return %s,err }; switch f.pc {\n", zero(e.fn.Result))
	for _, c := range e.nodes {
		fmt.Fprintf(w, "case %d:\n", e.states[c])
		e.emitCode(w, c, recursive)
		if resume, ok := e.resumes[c]; ok {
			fmt.Fprintf(w, "case %d:\nf.%s=returned; f.pc=%d\n", resume, slot(c.Bind.ID), e.states[c.Next])
		}
	}
	fmt.Fprintf(w, "default: return %s,ErrMalformed\n}\n}\n}\n", zero(e.fn.Result))
}
func (e *emitter) emitCode(w *bytes.Buffer, c *ir.Code, recursive bool) {
	switch c.Op {
	case "return":
		if recursive {
			fmt.Fprintf(w, "returned=f.%s; b.unframe(); stack=stack[:len(stack)-1]; if len(stack)==0 { return returned,nil }\n", slot(c.Var))
		} else {
			fmt.Fprintf(w, "return f.%s,nil\n", slot(c.Var))
		}
	case "let":
		v := c.Value
		if v.Kind == "constructor" {
			e.constructor(w, c)
			fmt.Fprintf(w, "f.pc=%d\n", e.states[c.Next])
			return
		}
		if v.Name == e.fn.Name {
			fmt.Fprintf(w, "if err:=b.frame(len(stack)); err!=nil { return %s,err }; next:=%s{pc:%d", zero(e.fn.Result), functionNames[e.fn.Name]+"Frame", e.states[e.fn.Body])
			for i, p := range e.fn.Params {
				fmt.Fprintf(w, ",%s:f.%s", slot(p.ID), slot(v.Args[i]))
			}
			fmt.Fprintf(w, "}; f.pc=%d; stack=append(stack,next)\n", e.resumes[c])
			return
		}
		fmt.Fprintf(w, "value,err:=%s(b", functionNames[v.Name])
		for _, id := range v.Args {
			fmt.Fprintf(w, ",f.%s", slot(id))
		}
		fmt.Fprintf(w, "); if err!=nil { return %s,err }; f.%s=value; f.pc=%d\n", zero(e.fn.Result), slot(c.Bind.ID), e.states[c.Next])
	case "cases":
		discr := "f." + slot(c.Var)
		if c.Type == "expr" {
			discr += ".kind"
		}
		fmt.Fprintf(w, "switch %s {\n", discr)
		for _, a := range c.Alts {
			fmt.Fprintf(w, "case %s:\n", e.caseValue(c.Type, a.Constructor))
			for i, p := range a.Params {
				field := []string{"left", "right"}[i]
				if p.Type == "tri" {
					field = "value"
				}
				if p.Type == "u32" {
					field = "id"
				}
				fmt.Fprintf(w, "f.%s=f.%s.%s\n", slot(p.ID), slot(c.Var), field)
			}
			fmt.Fprintf(w, "f.pc=%d\n", e.states[a.Body])
		}
		fmt.Fprintf(w, "default: return %s,ErrMalformed\n}\n", zero(e.fn.Result))
	}
}
func (e *emitter) ctor(name string) (string, int) {
	for _, t := range e.program.Types {
		for _, c := range t.Constructors {
			if c.Name == name {
				return t.Name, c.Tag
			}
		}
	}
	panic("validated constructor missing")
}
func (e *emitter) caseValue(t, name string) string {
	_, tag := e.ctor(name)
	switch t {
	case "bool":
		return []string{"false", "true"}[tag]
	case "tri":
		return fmt.Sprint(tag)
	case "expr":
		return []string{"Literal", "Variable", "Not", "And", "Or"}[tag]
	}
	panic("validated type missing")
}
func (e *emitter) constructor(w *bytes.Buffer, c *ir.Code) {
	t, tag := e.ctor(c.Value.Name)
	dest := "f." + slot(c.Bind.ID)
	if t != "expr" {
		fmt.Fprintf(w, "%s=%s\n", dest, e.caseValue(t, c.Value.Name))
		return
	}
	args := []string{"0", "0", "nil", "nil"}
	for i, id := range c.Value.Args {
		switch tag {
		case 0:
			args[0] = "f." + slot(id)
		case 1:
			args[1] = "f." + slot(id)
		default:
			args[i+2] = "f." + slot(id)
		}
	}
	fmt.Fprintf(w, "value,err:=b.make(%s,%s); if err!=nil { return %s,err }; %s=value\n", e.caseValue(t, c.Value.Name), strings.Join(args, ","), zero(e.fn.Result), dest)
}
