// Package modulegen compiles typed module IR into standalone pure Go packages.
package modulegen

import (
	"bytes"
	"crypto/sha256"
	"embed"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"go/format"
	"sort"
	"strings"

	"github.com/franchb/lean-go/internal/moduleir"
)

//go:embed templates/*.tmpl
var templates embed.FS

const Version = "lean-go-modulegen/v10"

func digest(data []byte) string { sum := sha256.Sum256(data); return hex.EncodeToString(sum[:]) }

type function struct {
	decl   moduleir.Function
	id     int
	nodes  []*moduleir.Code
	states map[*moduleir.Code]int
	slots  map[int]int
	joins  map[int]*moduleir.Join
}
type generator struct {
	program      *moduleir.Program
	api          *goAPI
	types        map[string]int
	constructors map[string]constructor
	functions    map[string]*function
}
type constructor struct{ typ, tag int }

// Generate validates the supplied IR before emitting any output. Source identity
// metadata is not authentication; use the source producer for Lean admission.
func Generate(p *moduleir.Program) (map[string][]byte, error) {
	if err := moduleir.Validate(p); err != nil {
		return nil, fmt.Errorf("validate module IR: %w", err)
	}
	g := newGenerator(p)
	var schema, control bytes.Buffer
	g.emitSchema(&schema)
	g.emitControl(&control)
	runtime, err := g.renderTemplate("runtime.go.tmpl")
	if err != nil {
		return nil, err
	}
	files := map[string][]byte{"runtime.go": runtime, "schema.go": schema.Bytes(), "control.go": control.Bytes()}
	if moduleir.HasTypedAPI(p.Schema) {
		g.api = newGoAPI(p)
		api, err := g.emitAPI()
		if err != nil {
			return nil, err
		}
		files["api.go"] = api
	}
	for name, data := range files {
		formatted, err := format.Source(data)
		if err != nil {
			return nil, fmt.Errorf("format %s: %w", name, err)
		}
		files[name] = formatted
	}
	manifest, err := g.manifest(files)
	if err != nil {
		return nil, err
	}
	files["manifest.json"] = manifest
	return files, nil
}
func newGenerator(p *moduleir.Program) *generator {
	g := &generator{program: p, types: map[string]int{"UInt32": 0}, constructors: map[string]constructor{}, functions: map[string]*function{}}
	for i, t := range p.Types {
		g.types[t.Name] = i + 1
		for _, c := range t.Constructors {
			g.constructors[c.Name] = constructor{i + 1, c.Tag}
		}
	}
	if moduleir.HasUInt64(p.Schema) {
		g.types["UInt64"] = len(p.Types) + 1
	}
	if moduleir.HasUInt8(p.Schema) {
		g.types["UInt8"] = len(p.Types) + 2
	}
	for i, d := range p.Functions {
		f := &function{decl: d, id: i, states: map[*moduleir.Code]int{}, slots: map[int]int{}, joins: map[int]*moduleir.Join{}}
		for _, param := range d.Params {
			f.slots[param.ID] = 0
		}
		f.collect(d.Body)
		ids := make([]int, 0, len(f.slots))
		for id := range f.slots {
			ids = append(ids, id)
		}
		sort.Ints(ids)
		for slot, id := range ids {
			f.slots[id] = slot
		}
		g.functions[d.Name] = f
	}
	return g
}
func (f *function) collect(c *moduleir.Code) {
	f.states[c] = len(f.nodes)
	f.nodes = append(f.nodes, c)
	if c.Op == "join" {
		f.joins[c.Join.ID] = c.Join
		for _, p := range c.Join.Params {
			f.slots[p.ID] = 0
		}
		f.collect(c.Join.Body)
		f.collect(c.Next)
	}
	if c.Op == "let" {
		f.slots[c.Bind.ID] = 0
		f.collect(c.Next)
	}
	if c.Op == "cases" {
		for _, a := range c.Alts {
			for _, p := range a.Params {
				f.slots[p.ID] = 0
			}
			f.collect(a.Body)
		}
	}
}
func (g *generator) emitSchema(w *bytes.Buffer) {
	w.WriteString("// Code generated by lean-go; DO NOT EDIT.\npackage extracted\n")
	w.WriteString("func typeName(t int)string{switch t{case 0:return \"UInt32\"\n")
	for _, t := range g.program.Types {
		fmt.Fprintf(w, "case %d:return %q\n", g.types[t.Name], t.Name)
	}
	if moduleir.HasUInt64(g.program.Schema) {
		fmt.Fprintf(w, "case %d:return %q\n", g.types["UInt64"], "UInt64")
	}
	if moduleir.HasUInt8(g.program.Schema) {
		fmt.Fprintf(w, "case %d:return %q\n", g.types["UInt8"], "UInt8")
	}
	w.WriteString("};return \"\"}\n")
	w.WriteString("func constructorName(t,tag int)string{switch t{\n")
	for _, t := range g.program.Types {
		fmt.Fprintf(w, "case %d:switch tag{\n", g.types[t.Name])
		for _, c := range t.Constructors {
			fmt.Fprintf(w, "case %d:return %q\n", c.Tag, c.Name)
		}
		w.WriteString("}\n")
	}
	w.WriteString("};return \"\"}\n")
	g.emitInputShape(w)
	w.WriteString("func fieldType(t,tag,index int)int{switch t{\n")
	for _, t := range g.program.Types {
		fmt.Fprintf(w, "case %d:switch tag{\n", g.types[t.Name])
		for _, c := range t.Constructors {
			if len(c.Fields) == 0 {
				continue
			}
			fmt.Fprintf(w, "case %d:switch index{\n", c.Tag)
			for i, field := range c.Fields {
				fmt.Fprintf(w, "case %d:return %d\n", i, g.types[field])
			}
			w.WriteString("}\n")
		}
		w.WriteString("}\n")
	}
	w.WriteString("};return -1}\n")
	g.emitRootMetadata(w)
}
func (g *generator) emitInputShape(w *bytes.Buffer) {
	wide := moduleir.HasUInt64(g.program.Schema)
	inactive32, inactiveADT, inactive64 := "", "", ""
	if wide {
		inactive32 = "&&in.UInt64==0"
		inactiveADT = "||in.UInt64!=0"
	}
	if moduleir.HasUInt8(g.program.Schema) {
		inactive32 += "&&in.UInt8==0"
		inactive64 = "&&in.UInt8==0"
		inactiveADT += "||in.UInt8!=0"
		fmt.Fprintf(w, "func inputShape(in *Input)(int,int,bool){if len(in.Type)>512||len(in.Constructor)>512{return 0,0,false};if in.Type==\"UInt8\"{return %d,0,in.Constructor==\"\"&&len(in.Fields)==0&&in.UInt32==0&&in.UInt64==0};return inputOtherShape(in)}\n", g.types["UInt8"])
	}
	shapeName := "inputShape"
	if moduleir.HasUInt8(g.program.Schema) {
		shapeName = "inputOtherShape"
	}
	fmt.Fprintf(w, "func %s(in *Input)(int,int,bool){if len(in.Type)>512||len(in.Constructor)>512{return 0,0,false};switch in.Type{case \"UInt32\":return 0,0,in.Constructor==\"\"&&len(in.Fields)==0%s\n", shapeName, inactive32)
	if wide {
		fmt.Fprintf(w, "case \"UInt64\":return %d,0,in.Constructor==\"\"&&len(in.Fields)==0&&in.UInt32==0%s\n", g.types["UInt64"], inactive64)
	}
	for _, t := range g.program.Types {
		fmt.Fprintf(w, "case %q:if in.UInt32!=0%s{return 0,0,false};switch in.Constructor{\n", t.Name, inactiveADT)
		for _, c := range t.Constructors {
			fmt.Fprintf(w, "case %q:return %d,%d,len(in.Fields)==%d\n", c.Name, g.types[t.Name], c.Tag, len(c.Fields))
		}
		w.WriteString("}\n")
	}
	w.WriteString("};return 0,0,false}\n")
}

func (g *generator) emitControl(w *bytes.Buffer) {
	w.WriteString("// Code generated by lean-go; DO NOT EDIT.\npackage extracted\n")
	w.WriteString(`type frame struct {function,pc,destination int;slots []*node}
// frameForCall reuses only the retired frame at the next depth. Clear its old
// slot length before shrinking so the unused tail does not retain earlier nodes.
func frameForCall(stack []frame,function,destination,count int)frame{
 var slots []*node
 if len(stack)<cap(stack){slots=stack[:len(stack)+1][len(stack)].slots}
 if cap(slots)<count{slots=make([]*node,count)}else{clear(slots);slots=slots[:count]}
 return frame{function:function,destination:destination,slots:slots}
}
`)
	g.emitInitialFrame(w)
	w.WriteString("stack:=[]frame{initial};for{if err:=b.step();err!=nil{return nil,err};f:=&stack[len(stack)-1];switch f.function{\n")
	for _, decl := range g.program.Functions {
		f := g.functions[decl.Name]
		fmt.Fprintf(w, "case %d:switch f.pc{\n", f.id)
		for _, c := range f.nodes {
			fmt.Fprintf(w, "case %d:\n", f.states[c])
			g.emitCode(w, f, c)
		}
		w.WriteString("default:return nil,ErrMalformed}\n")
	}
	w.WriteString("default:return nil,ErrMalformed}\n}\n}\n")
}
func (g *generator) emitCode(w *bytes.Buffer, f *function, c *moduleir.Code) {
	switch c.Op {
	case "join":
		fmt.Fprintf(w, "f.pc=%d\n", f.states[c.Next])
	case "jump":
		g.emitJump(w, f, c)
	case "return":
		fmt.Fprintf(w, "value:=f.slots[%d];destination:=f.destination;stack=stack[:len(stack)-1];if len(stack)==0{return value,nil};stack[len(stack)-1].slots[destination]=value\n", f.slots[c.Var])
	case "cases":
		fmt.Fprintf(w, "if f.slots[%d]==nil{return nil,ErrMalformed};switch f.slots[%d].tag{\n", f.slots[c.Var], f.slots[c.Var])
		for _, a := range c.Alts {
			fmt.Fprintf(w, "case %d:\n", g.constructors[a.Constructor].tag)
			for i, p := range a.Params {
				fmt.Fprintf(w, "f.slots[%d]=f.slots[%d].fields[%d]\n", f.slots[p.ID], f.slots[c.Var], i)
			}
			fmt.Fprintf(w, "f.pc=%d\n", f.states[a.Body])
		}
		w.WriteString("default:return nil,ErrMalformed}\n")
	case "let":
		switch c.Value.Kind {
		case "uint8", "uint32", "uint64", "primitive":
			g.emitNumeric(w, f, c)
		case "constructor":
			ctor := g.constructors[c.Value.Name]
			fmt.Fprintf(w, "value,err:=b.make(%d,%d,[]*node{", ctor.typ, ctor.tag)
			for _, id := range c.Value.Args {
				fmt.Fprintf(w, "f.slots[%d],", f.slots[id])
			}
			fmt.Fprintf(w, "});if err!=nil{return nil,err};f.slots[%d]=value;f.pc=%d\n", f.slots[c.Bind.ID], f.states[c.Next])
		case "call":
			callee := g.functions[c.Value.Name]
			fmt.Fprintf(w, "if err:=b.enter(%d,len(stack));err!=nil{return nil,err}\n", len(callee.slots))
			fmt.Fprintf(w, "next:=frameForCall(stack,%d,%d,%d)\n", callee.id, f.slots[c.Bind.ID], len(callee.slots))
			for i, p := range callee.decl.Params {
				fmt.Fprintf(w, "next.slots[%d]=f.slots[%d]\n", callee.slots[p.ID], f.slots[c.Value.Args[i]])
			}
			fmt.Fprintf(w, "f.pc=%d;stack=append(stack,next)\n", f.states[c.Next])
		}
	}
}
func (g *generator) manifest(files map[string][]byte) ([]byte, error) {
	canonical, err := json.Marshal(g.program)
	if err != nil {
		return nil, err
	}
	hashes := map[string]string{}
	for n, b := range files {
		hashes[n] = digest(b)
	}
	functions := map[string]int{}
	for n, f := range g.functions {
		functions[n] = f.id
	}
	constructors := map[string][2]int{}
	for n, c := range g.constructors {
		constructors[n] = [2]int{c.typ, c.tag}
	}
	manifest := struct {
		Schema          string                `json:"schema"`
		Generator       string                `json:"generator"`
		GeneratorSource string                `json:"generator_source_sha256"`
		ValidatorSource string                `json:"validator_source_sha256"`
		IR              string                `json:"ir_sha256"`
		Program         *moduleir.Program     `json:"program"`
		Functions       map[string]int        `json:"function_ids"`
		Constructors    map[string][2]int     `json:"constructor_ids"`
		Files           map[string]string     `json:"generated_files"`
		Evidence        string                `json:"evidence"`
		Primitives      *[]moduleir.Primitive `json:"primitives,omitempty"`
		GoAPI           *goAPI                `json:"go_api,omitempty"`
	}{Schema: strings.Replace(g.program.Schema, "lean-go-ir/", "lean-go-manifest/", 1), Generator: Version, GeneratorSource: SourceDigest(), ValidatorSource: moduleir.SourceDigest(), IR: digest(canonical), Program: g.program, Functions: functions, Constructors: constructors, Files: hashes, Evidence: "Tested/trusted extraction; not an end-to-end proof of Go correctness. Target execution must be tested separately."}
	// Every validated module schema uses the corresponding manifest version.
	if g.program.Schema != moduleir.Schema {
		primitives := g.primitiveCatalog()
		manifest.Primitives = &primitives
	}
	if moduleir.HasTypedAPI(g.program.Schema) {
		manifest.GoAPI = g.api
	}
	data, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}
