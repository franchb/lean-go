// PublishPackage installs a complete newly generated package or verifies
// identical output. Differing existing output is refused and preserved unless
// replace is set; then a directory that is recognizably a previous lean-go
// package is swapped for the new one, with rollback if the swap fails.
// Cooperating writers serialize through an exclusive sibling lock.
func PublishPackage(dir string, files map[string][]byte, replace bool) error {
	if len(files) == 0 {
		return fmt.Errorf("empty generated package")
	}
	for name := range files {
		if name == "" || name == "." || name == ".." || filepath.Base(name) != name || strings.ContainsAny(name, "/\\\x00") {
			return fmt.Errorf("unsafe generated filename %q", name)
		}
	}
	if strings.TrimSpace(dir) == "" {
		return fmt.Errorf("empty destination")
	}
	absolute, err := filepath.Abs(dir)
	if err != nil {
		return err
	}
	base := filepath.Base(absolute)
	if base == "." || base == string(filepath.Separator) {
		return fmt.Errorf("unsafe destination")
	}
	parent := filepath.Dir(absolute)
	if err = plainDirectory(parent); err != nil {
		return fmt.Errorf("unsafe parent: %w", err)
	}
	lock := filepath.Join(parent, "."+base+".lean-go.lock")
	if err = os.Mkdir(lock, 0o700); err != nil {
		return fmt.Errorf("acquire publication lock: %w", err)
	}
	defer os.Remove(lock)
	same, err := matches(absolute, files)
	if same {
		return nil
	}
	if err != nil && (!replace || !isDiffers(err)) {
		return err
	}
	stage, err := os.MkdirTemp(parent, "."+base+".lean-go-stage-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(stage)
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		if err = os.WriteFile(filepath.Join(stage, name), files[name], 0o644); err != nil {
			return err
		}
	}
	same, err = matches(absolute, files)
	if same {
		return nil
	}
	if err == nil {
		if err = os.Rename(stage, absolute); err != nil {
			return fmt.Errorf("publish staged package: %w", err)
		}
		return nil
	}
	if !replace || !isDiffers(err) {
		return err
	}
	if err := replaceable(absolute, files); err != nil {
		return err
	}
	backup := stage + ".previous"
	if err := os.Rename(absolute, backup); err != nil {
		return fmt.Errorf("move previous package aside: %w", err)
	}
	if err := os.Rename(stage, absolute); err != nil {
		if restore := os.Rename(backup, absolute); restore != nil {
			return fmt.Errorf("publish staged package: %v; previous package retained at %s", err, backup)
		}
		return fmt.Errorf("publish staged package: %w", err)
	}
	return os.RemoveAll(backup)
}

// differs marks existing output that is valid but not identical.
type differs struct{ text string }

func (d *differs) Error() string { return d.text }

func isDiffers(err error) bool {
	var d *differs
	return errors.As(err, &d)
}

// replaceable accepts only a flat directory of regular files that a previous
// lean-go run generated, in either mode: a manifest naming the other files,
// nothing else.
func replaceable(dir string, files map[string][]byte) error {
	refuse := fmt.Errorf("refusing to replace %s: it is not a package generated by lean-go", dir)
	data, err := os.ReadFile(filepath.Join(dir, "manifest.json"))
	if err != nil {
		return refuse
	}
	value, err := ParseJSON(data)
	if err != nil {
		return refuse
	}
	manifest, ok := value.(*Object)
	schema, _ := manifest.Values["schema"].(string)
	generated, isObject := manifest.Values["generated_files"].(*Object)
	generatedSchema := strings.HasPrefix(schema, "lean-go-manifest/") || strings.HasPrefix(schema, "lean-go-native-manifest/")
	if !ok || !generatedSchema || !isObject {
		return refuse
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		info, err := os.Lstat(filepath.Join(dir, entry.Name()))
		if err != nil || !info.Mode().IsRegular() {
			return refuse
		}
		_, known := generated.Values[entry.Name()]
		if _, fresh := files[entry.Name()]; !known && !fresh && entry.Name() != "manifest.json" {
			return refuse
		}
	}
	return nil
}

func plainDirectory(path string) error {
	absolute, err := filepath.Abs(path)
	if err != nil {
		return err
	}
	for current := absolute; ; current = filepath.Dir(current) {
		info, err := os.Lstat(current)
		if err != nil {
			return err
		}
		if info.Mode()&os.ModeSymlink != 0 || !info.IsDir() {
			return fmt.Errorf("not a plain directory: %s", current)
		}
		if filepath.Dir(current) == current {
			break
		}
	}
	return nil
}

func matches(dir string, files map[string][]byte) (bool, error) {
	info, err := os.Lstat(dir)
	if os.IsNotExist(err) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	if info.Mode()&os.ModeSymlink != 0 || !info.IsDir() {
		return false, fmt.Errorf("destination is not a plain directory")
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return false, err
	}
	if len(entries) != len(files) {
		return false, &differs{"existing output file set differs"}
	}
	for _, entry := range entries {
		expected, ok := files[entry.Name()]
		if !ok {
			return false, &differs{fmt.Sprintf("unexpected existing output %q", entry.Name())}
		}
		info, err := entry.Info()
		if err != nil {
			return false, err
		}
		if !info.Mode().IsRegular() || entry.Type()&fs.ModeSymlink != 0 {
			return false, fmt.Errorf("unsafe existing output %q", entry.Name())
		}
		actual, err := os.ReadFile(filepath.Join(dir, entry.Name()))
		if err != nil {
			return false, err
		}
		if !bytes.Equal(actual, expected) {
			return false, &differs{"existing output differs: " + entry.Name()}
		}
	}
	return true, nil
}

// PublishFile atomically writes one file unless identical bytes already exist.
// IR publication creates missing parents; evidence publication requires a
// regular-file destination in an existing directory.
func PublishFile(path string, data []byte, ir bool) error {
	if ir {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if isSymlink(path) {
			return exportError("IR output must not be a symlink")
		}
	} else {
		if isSymlink(path) || (exists(path) && !isFile(path)) {
			return exportError("output must be a regular file, not a symlink")
		}
		if !isDir(filepath.Dir(path)) {
			return exportError("output parent does not exist")
		}
	}
	if existing, err := os.ReadFile(path); err == nil && bytes.Equal(existing, data) {
		return nil
	}
	temporary, err := os.CreateTemp(filepath.Dir(path), ".lean-go-publish-")
	if err != nil {
		return err
	}
	name := temporary.Name()
	defer os.Remove(name)
	if _, err := temporary.Write(data); err != nil {
		temporary.Close()
		return err
	}
	if err := temporary.Sync(); err != nil {
		temporary.Close()
		return err
	}
	if err := temporary.Close(); err != nil {
		return err
	}
	if err := os.Chmod(name, 0o644); err != nil {
		return err
	}
	return os.Rename(name, path)
}
