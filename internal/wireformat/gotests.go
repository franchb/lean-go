func (w *Word) goRead(data string) string {
	order := "BigEndian"
	if w.Little {
		order = "LittleEndian"
	}
	end := w.Offset + w.Size
	switch w.Size {
	case 1:
		return fmt.Sprintf("uint64(%s[%d])", data, w.Offset)
	case 2:
		return fmt.Sprintf("uint64(binary.%s.Uint16(%s[%d:%d]))", order, data, w.Offset, end)
	case 4:
		return fmt.Sprintf("uint64(binary.%s.Uint32(%s[%d:%d]))", order, data, w.Offset, end)
	}
	return fmt.Sprintf("binary.%s.Uint64(%s[%d:%d])", order, data, w.Offset, end)
}

func (w *Word) goWrite(raw, value string) string {
	order := "BigEndian"
	if w.Little {
		order = "LittleEndian"
	}
	end := w.Offset + w.Size
	switch w.Size {
	case 1:
		return fmt.Sprintf("%s[%d] = byte(%s)", raw, w.Offset, value)
	case 2:
		return fmt.Sprintf("binary.%s.PutUint16(%s[%d:%d], uint16(%s))", order, raw, w.Offset, end, value)
	case 4:
		return fmt.Sprintf("binary.%s.PutUint32(%s[%d:%d], uint32(%s))", order, raw, w.Offset, end, value)
	}
	return fmt.Sprintf("binary.%s.PutUint64(%s[%d:%d], %s)", order, raw, w.Offset, end, value)
}

func (s *Sub) goExtract(word string) string {
	if s.Whole() {
		return word
	}
	return fmt.Sprintf("(%s >> %d) & %#x", word, s.Shift, maxOf(s.Width))
}

// goCheck renders the failure condition of a check on v (a uint64).
func goFails(c *Check, v string) string {
	s := c.Sub
	switch c.Kind {
	case CheckConst:
		return fmt.Sprintf("%s != %d", v, s.Const)
	case CheckReserved:
		return v + " != 0"
	case CheckWidth:
		return fmt.Sprintf("%s > %#x", v, maxOf(s.Width))
	case CheckEnum:
		var alts []string
		for _, e := range s.Enum {
			alts = append(alts, fmt.Sprintf("%s != %d", v, e))
		}
		return strings.Join(alts, " && ")
	case CheckMin:
		return fmt.Sprintf("%s < %d", v, *s.Min)
	}
	return fmt.Sprintf("%s > %d", v, *s.Max)
}

