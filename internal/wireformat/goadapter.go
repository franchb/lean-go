package wireformat

import (
	"fmt"
	"go/format"
	"strings"
)

// The adapter is split in two files. <name>.go is plain Go over []byte: it
// defines Header, the typed errors and the public functions, and it decides
// nothing about the format itself. lean.go is the backend glue that calls
// the native extracted package; it is the only file that knows the
// extracted API (see backendNative in gobackend.go).

func goType(bits int) string { return fmt.Sprintf("uint%d", bits) }
func goField(s *Sub) string  { return cap1(s.Name) }
func goReason(r string) string {
	return "Reason" + cap1(r)
}

// reasonInfo describes one Reason constant.
type reasonInfo struct {
	Name, Field, Text string
}

func (f *Format) reasons() []reasonInfo {
	out := []reasonInfo{{"ReasonTruncated", "", "fewer bytes than the header size"}}
	if f.Payload != nil {
		out = append(out,
			reasonInfo{"ReasonPayloadTruncated", f.Payload.Name, "fewer payload bytes than the header declares"},
			reasonInfo{"ReasonPayloadLengthMismatch", f.Payload.Name, "the payload length differs from the length field"})
	}
	seen := map[string]bool{}
	for _, list := range [][]*Check{f.Parse, f.Valid} {
		for _, c := range list {
			if seen[c.Reason] {
				continue
			}
			seen[c.Reason] = true
			out = append(out, reasonInfo{goReason(c.Reason), c.Sub.Name, checkText(c)})
		}
	}
	return out
}

func checkText(c *Check) string {
	s := c.Sub
	switch c.Kind {
	case CheckConst:
		return fmt.Sprintf("value is not the constant %d", s.Const)
	case CheckReserved:
		return "reserved bits are not zero"
	case CheckWidth:
		return fmt.Sprintf("value does not fit in %d bits", s.Width)
	case CheckEnum:
		var vs []string
		for _, v := range s.Enum {
			vs = append(vs, fmt.Sprint(v))
		}
		return "value is not one of " + strings.Join(vs, ", ")
	case CheckMin:
		return fmt.Sprintf("value is below the minimum %d", *s.Min)
	}
	return fmt.Sprintf("value is above the maximum %d", *s.Max)
}

func describeSub(s *Sub) string {
	w := s.Word
	var where string
	if w.Size == 1 {
		where = fmt.Sprintf("byte %d", w.Offset)
	} else {
		order := "big-endian"
		if w.Little {
			order = "little-endian"
		}
		where = fmt.Sprintf("bytes %d..%d, %s", w.Offset, w.Offset+w.Size-1, order)
	}
	if !s.Whole() {
		where += fmt.Sprintf(", bits %d..%d", s.Shift, s.Shift+s.Width-1)
	}
	var cons []string
	switch s.Role {
	case RoleConst:
		cons = append(cons, fmt.Sprintf("must be %d", s.Const))
	case RoleReserved:
		cons = append(cons, "must be zero")
	}
	if s.Enum != nil {
		var vs []string
		for _, v := range s.Enum {
			vs = append(vs, fmt.Sprint(v))
		}
		cons = append(cons, "one of "+strings.Join(vs, ", "))
	}
	if s.Min != nil {
		cons = append(cons, fmt.Sprintf("at least %d", *s.Min))
	}
	if s.Max != nil {
		cons = append(cons, fmt.Sprintf("at most %d", *s.Max))
	}
	if len(cons) > 0 {
		where += "; " + strings.Join(cons, ", ")
	}
	return where
}

func gofmt(name, src string) string {
	out, err := format.Source([]byte(src))
	if err != nil {
		panic(fmt.Sprintf("wireformat: generated %s does not parse: %v\n%s", name, err, src))
	}
	return string(out)
}

// GoFiles renders the adapter package and its generated tests.
func (f *Format) GoFiles() map[string]string {
	return map[string]string{
		f.Name + ".go":          gofmt(f.Name+".go", f.adapterGo()),
		"lean.go":               gofmt("lean.go", backendNative(f)),
		f.Name + "_gen_test.go": gofmt(f.Name+"_gen_test.go", f.testsGo()),
	}
}

func (f *Format) adapterGo() string {
	var b strings.Builder
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	p("// Code generated by lean-go format from the %s spec; DO NOT EDIT.\n\n", f.Name)
	desc := f.Description
	if desc == "" {
		desc = "the " + f.Name + " header."
	}
	p("// Package %s parses and serializes %s-byte headers: %s\n", f.Name, fmt.Sprint(f.Size), desc)
	p(`//
// Every decision is made by Go code extracted from ordinary Lean definitions
// (../source) whose properties are kernel-checked (../proof): Parse accepts
// exactly the byte strings that satisfy every declared constraint and reports
// the first failing check, and Parse and AppendSerialize are mutually inverse
// on valid headers, so every accepted header has exactly one encoding. This
// package only moves bytes. It never panics, never modifies the caller's
// slices and keeps no reference to them.
`)
	p("package %s\n\n", f.Name)
	p("import (\n\t\"errors\"\n\t\"fmt\"\n\t\"io\"\n")
	if f.Payload != nil {
		p("\t\"math\"\n\t\"slices\"\n")
	}
	p(")\n\n")
	p("// HeaderSize is the encoded header length in bytes.\nconst HeaderSize = %d\n\n", f.Size)
	p("// Header holds the decoded fields. Constant and reserved fields are not\n// stored: Parse checks them and AppendSerialize writes them.\ntype Header struct {\n")
	for _, s := range f.Fields {
		desc := describeSub(s)
		if s == f.Payload {
			desc += "; the payload length"
			if f.HeaderBytes != 0 {
				desc += fmt.Sprintf(" plus the %d header bytes", f.HeaderBytes)
			}
		}
		p("\t%s %s // %s\n", goField(s), goType(s.Type), desc)
	}
	p("}\n\n")
	p("// Reason says why bytes were rejected or a Header is invalid.\ntype Reason uint8\n\nconst (\n")
	reasons := f.reasons()
	for i, r := range reasons {
		if i == 0 {
			p("\t%s Reason = iota + 1 // %s\n", r.Name, r.Text)
		} else {
			field := ""
			if r.Field != "" {
				field = r.Field + ": "
			}
			p("\t%s // %s%s\n", r.Name, field, r.Text)
		}
	}
	p(")\n\nvar reasonText = [...]string{\n")
	for _, r := range reasons {
		text := r.Text
		if r.Field != "" {
			text = r.Field + ": " + r.Text
		}
		p("\t%s: %q,\n", r.Name, text)
	}
	p("}\n\nvar reasonField = [...]string{\n")
	for _, r := range reasons {
		if r.Field != "" {
			p("\t%s: %q,\n", r.Name, r.Field)
		}
	}
	p("}\n\n")
	p(`func (r Reason) String() string {
	if int(r) < len(reasonText) && reasonText[r] != "" {
		return reasonText[r]
	}
	return fmt.Sprintf("reason(%%d)", uint8(r))
}

// Field names the spec field a reason refers to, or "".
func (r Reason) Field() string {
	if int(r) < len(reasonField) {
		return reasonField[r]
	}
	return ""
}

// Error reports a rejected input or an invalid Header.
type Error struct {
	Reason Reason
	// Missing is the number of further bytes needed when Reason is a truncation.
	Missing uint64
}

func (e *Error) Error() string {
	if e.Missing != 0 {
		return fmt.Sprintf("%s: %%s (%%d more bytes needed)", e.Reason, e.Missing)
	}
	return "%s: " + e.Reason.String()
}

// Is reports truncations as io.ErrUnexpectedEOF.
func (e *Error) Is(target error) bool {
	return target == io.ErrUnexpectedEOF && e.truncated()
}

func (e *Error) truncated() bool {
	return e.Reason == ReasonTruncated%s
}

// ErrInternal wraps an unexpected result of the extracted code. The extracted
// functions are total and have no resource limits, so it indicates a bug, not
// bad input.
var ErrInternal = errors.New("%s: internal codec failure")

func internal(err error) error { return fmt.Errorf("%%w: %%v", ErrInternal, err) }

// Validate reports whether h can be serialized: every field fits its width
// and satisfies its declared constraints. It returns nil or an *Error.
func Validate(h Header) error {
	return validate(&h)
}

// validate is Validate on a header passed by pointer. Header is copied in
// memory whenever it is passed by value, so the adapter passes it by pointer
// internally.
func validate(h *Header) error {
	reason, err := leanValidate(h)
	if err != nil {
		return err
	}
	if reason != 0 {
		return &Error{Reason: reason}
	}
	return nil
}

// AppendSerialize appends the encoding of h to dst. On error it returns dst
// unchanged, without writing to its spare capacity.
func AppendSerialize(dst []byte, h Header) ([]byte, error) {
	if err := validate(&h); err != nil {
		return dst, err
	}
	return leanSerialize(dst, &h)
}
`, f.Name, f.Name, payloadTrunc(f), f.Name)
	if f.Payload == nil {
		p(`
// Parse decodes the header at the start of data. It returns the header and
// the number of bytes consumed (HeaderSize); bytes after the header are not
// examined. On failure it returns an *Error and consumes nothing: input
// shorter than HeaderSize gives ReasonTruncated (matching
// io.ErrUnexpectedEOF), otherwise the reason of the first failing check.
func Parse(data []byte) (Header, int, error) {
	if len(data) < HeaderSize {
		return Header{}, 0, &Error{Reason: ReasonTruncated, Missing: uint64(HeaderSize - len(data))}
	}
	var raw [HeaderSize]byte
	copy(raw[:], data)
	var h Header
	reason, err := leanParse(&raw, &h)
	if err != nil {
		return Header{}, 0, err
	}
	if reason != 0 {
		return Header{}, 0, &Error{Reason: reason}
	}
	return h, HeaderSize, nil
}
`)
		return b.String()
	}
	p(`
// Parse decodes the header at the start of data and the payload it declares.
// It returns the header, the number of bytes consumed (header and payload)
// and the payload, a sub-slice of data whose capacity equals its length, so
// appending to it cannot overwrite later bytes. Copy the payload to keep it
// beyond the lifetime of data. On failure it returns an *Error and consumes
// nothing: a short header gives ReasonTruncated and a short payload
// ReasonPayloadTruncated (both match io.ErrUnexpectedEOF, with Missing set);
// otherwise the reason is the first failing check of a complete header.
func Parse(data []byte) (Header, int, []byte, error) {
	if len(data) < HeaderSize {
		return Header{}, 0, nil, &Error{Reason: ReasonTruncated, Missing: uint64(HeaderSize - len(data))}
	}
	var raw [HeaderSize]byte
	copy(raw[:], data)
	var h Header
	reason, err := leanParse(&raw, &h)
	if err != nil {
		return Header{}, 0, nil, err
	}
	if reason != 0 {
		return Header{}, 0, nil, &Error{Reason: reason}
	}
	available := uint32(math.MaxUint32)
	if rest := len(data) - HeaderSize; uint64(rest) < uint64(available) {
		available = uint32(rest)
	}
	count, complete, err := leanClassify(&h, available)
	if err != nil {
		return Header{}, 0, nil, err
	}
	if !complete {
		return Header{}, 0, nil, &Error{Reason: ReasonPayloadTruncated, Missing: uint64(count)}
	}
	if uint64(count) > uint64(available) {
		return Header{}, 0, nil, internal(errors.New("payload count exceeds the available bytes"))
	}
	end := HeaderSize + int(count)
	return h, end, data[HeaderSize:end:end], nil
}

// PayloadLength returns the payload byte count h declares.
func PayloadLength(h Header) (uint32, error) {
	// With nothing available the decision reports the whole declared count.
	count, _, err := leanClassify(&h, 0)
	return count, err
}

// AppendFrame appends the encoding of h followed by payload to dst. The
// length field of h must already describe payload. payload may overlap dst.
// On error it returns dst unchanged, without writing to its spare capacity.
func AppendFrame(dst []byte, h Header, payload []byte) ([]byte, error) {
	if err := validate(&h); err != nil {
		return dst, err
	}
	want, _, err := leanClassify(&h, 0)
	if err != nil {
		return dst, err
	}
	if uint64(len(payload)) != uint64(want) {
		return dst, &Error{Reason: ReasonPayloadLengthMismatch}
	}
	// The header is encoded before anything is written: payload may occupy
	// the bytes it will use.
	var buf [HeaderSize]byte
	raw, err := leanSerialize(buf[:0], &h)
	if err != nil {
		return dst, err
	}
	start := len(dst)
	dst = slices.Grow(dst, len(raw)+len(payload))[:start+len(raw)+len(payload)]
	// Move the payload first: it may occupy the bytes the header will use.
	copy(dst[start+len(raw):], payload)
	copy(dst[start:], raw)
	return dst, nil
}
`)
	return b.String()
}

func payloadTrunc(f *Format) string {
	if f.Payload == nil {
		return ""
	}
	return " || e.Reason == ReasonPayloadTruncated"
}
