// backendNative renders lean.go for the native extracted package: plain Go
// structs and total functions, with no limits or budgets.
//
// The adapter needs exactly four functions from a backend:
//
//	leanParse(raw *[HeaderSize]byte, h *Header) (Reason, error)
//	leanValidate(h *Header) (Reason, error)
//	leanSerialize(dst []byte, h *Header) ([]byte, error)
//	leanClassify(h *Header, available uint32) (count uint32, complete bool, err error)
//
// leanParse stores the parsed header in *h when it returns no reason and no
// error; on any other result *h is unspecified (the native backend zeroes
// it) and the adapter does not read it. leanSerialize appends exactly
// HeaderSize bytes, or on error returns dst unchanged without writing to its
// spare capacity.
//
// Headers travel by pointer inside the adapter. Header has more fields than
// Go keeps in registers, so every by-value pass or return is a memory copy,
// and a copy that reads a header just written field by field cannot be
// forwarded from the store buffer and stalls; these copies, not the
// extracted code, dominated the cost of Parse and AppendSerialize.
//
// The native functions cannot fail; the error results remain for an
// unexpected constructor, which checkNativeAPI and the generated tests rule
// out, so the adapter is the same for every backend.
func backendNative(f *Format) string {
	var b strings.Builder
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	p("// Code generated by lean-go-format from the %s spec; DO NOT EDIT.\n\n", f.Name)
	p("// Backend glue for the native extracted package: plain Go values and total\n")
	p("// functions, with no resource limits. It converts values and maps results;\n")
	p("// it makes no decisions about the format.\n\n")
	p("package %s\n\nimport (\n\t\"errors\"\n\n\tcodec %q\n)\n\n", f.Name, f.ExtractedImport())
	p("var errUnexpected = errors.New(\"unexpected value from the extracted code\")\n\n")

	// Header and the extracted Header have the same fields, names, types and
	// order, so they and pointers to them convert directly; a mismatch fails
	// to compile.
	p("func toLean(h *Header) codec.Header { return codec.Header(*h) }\n\n")

	p("func leanParse(raw *[HeaderSize]byte, h *Header) (Reason, error) {\n\tr := codec.Parse(codec.Wire{")
	for i := range f.Size {
		if i > 0 {
			p(", ")
		}
		p("B%d: raw[%d]", i, i)
	}
	p("})\n")
	// Assigning AsOk's result through the converted pointer stores the
	// header once, straight into the caller's variable.
	p("\tvar ok bool\n\tif *(*codec.Header)(h), ok = r.AsOk(); ok {\n\t\treturn 0, nil\n\t}\n")
	if len(f.Parse) > 0 {
		p("\tswitch {\n")
		for _, c := range f.Parse {
			p("\tcase r.Is%s():\n\t\treturn %s, nil\n", cap1(c.Reason), goReason(c.Reason))
		}
		p("\t}\n")
	}
	p("\treturn 0, internal(errUnexpected)\n}\n\n")

	p("func leanValidate(h *Header) (Reason, error) {\n\tr := codec.Validate(toLean(h))\n")
	p("\tswitch {\n\tcase r.IsValid():\n\t\treturn 0, nil\n")
	for _, c := range f.Valid {
		p("\tcase r.Is%s():\n\t\treturn %s, nil\n", cap1(c.Reason), goReason(c.Reason))
	}
	p("\t}\n\treturn 0, internal(errUnexpected)\n}\n\n")

	// Appending the bytes one by one writes them straight into dst; an
	// intermediate [HeaderSize]byte would be stored byte by byte and then
	// reloaded in words, which stalls.
	p("func leanSerialize(dst []byte, h *Header) ([]byte, error) {\n\tw := codec.Serialize(toLean(h))\n\treturn append(dst")
	for i := range f.Size {
		p(", w.B%d", i)
	}
	p("), nil\n}\n")

	if f.Payload != nil {
		p(`
func leanClassify(h *Header, available uint32) (uint32, bool, error) {
	r := codec.Classify(toLean(h), available)
	if n, ok := r.AsComplete(); ok {
		return n, true, nil
	}
	if n, ok := r.AsNeedMore(); ok {
		return n, false, nil
	}
	return 0, false, internal(errUnexpected)
}
`)
	}
	return b.String()
}

// checkNativeAPI compares the Go API recorded in a native manifest with the
// names lean.go uses, so a renamed type, field, method or function is
// reported by the generator instead of as a compile error in the output.
func checkNativeAPI(f *Format, manifest []byte) error {
	var m struct {
		Schema string        `json:"schema"`
		Mode   string        `json:"mode"`
		API    nativegen.API `json:"go_api"`
	}
	if err := json.Unmarshal(manifest, &m); err != nil {
		return fmt.Errorf("native manifest: %w", err)
	}
	if m.Schema != nativegen.ManifestSchema || m.Mode != "native" {
		return fmt.Errorf("extracted package is not native: schema %q, mode %q", m.Schema, m.Mode)
	}
	var problems []string
	bad := func(format string, args ...any) { problems = append(problems, fmt.Sprintf(format, args...)) }
	roots := map[string]string{"parse": "Parse", "serialize": "Serialize", "validate": "Validate"}
	if f.Payload != nil {
		roots["classify"] = "Classify"
	}
	for lean, want := range roots {
		got, ok := m.API.Functions[f.Module+"."+lean]
		if !ok || got.Go != want || got.Error || got.ByteFold != "" {
			bad("root %s.%s is %+v, want %s without an error result", f.Module, lean, got, want)
		}
	}
	var fields, wire []string
	for _, s := range f.Fields {
		fields = append(fields, goField(s))
	}
	for i := range f.Size {
		wire = append(wire, fmt.Sprintf("B%d", i))
	}
	for name, want := range map[string][]string{"Header": fields, "Wire": wire} {
		got := m.API.Types[name]
		if got.Go != name || got.Kind != "record" || !slices.Equal(got.Fields, want) {
			bad("type %s is %+v, want a record with fields %v", name, got, want)
		}
	}
	sum := func(name string, is []string, as ...string) {
		got := m.API.Types[name]
		if got.Go != name || got.Kind != "sum" {
			bad("type %s is %+v, want a sum", name, got)
			return
		}
		for _, c := range is {
			if got.Is[name+"."+c] != "Is"+cap1(c) {
				bad("%s.%s has no method Is%s", name, c, cap1(c))
			}
		}
		for _, c := range as {
			if got.As[name+"."+c] != "As"+cap1(c) {
				bad("%s.%s has no method As%s", name, c, cap1(c))
			}
		}
	}
	reasons := func(checks []*Check, first string) []string {
		out := []string{first}
		for _, c := range checks {
			out = append(out, c.Reason)
		}
		return out
	}
	sum("ParseResult", reasons(f.Parse, "ok"), "ok")
	sum("Validity", reasons(f.Valid, "valid"))
	if f.Payload != nil {
		sum("Availability", []string{"needMore", "complete"}, "needMore", "complete")
	}
	if len(problems) > 0 {
		slices.Sort(problems)
		return fmt.Errorf("native extracted API differs from the adapter backend: %s", strings.Join(problems, "; "))
	}
	return nil
}
