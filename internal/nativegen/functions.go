package nativegen

import (
	"bytes"
	"fmt"
	"strings"

	"github.com/franchb/lean-go/internal/moduleir"
)

const header = "// Code generated by lean-go (native mode); DO NOT EDIT.\n\npackage extracted\n"

func (m *model) emitFunctions(w *bytes.Buffer, used map[string]bool) error {
	w.WriteString(header)
	for _, decl := range m.program.Functions {
		f := m.funcs[decl.Name]
		if f.fold != nil {
			m.emitFold(w, f)
		}
		if f.elided {
			continue
		}
		if f.root && f.depth && f.fold == nil {
			m.emitDepthWrapper(w, f)
		}
		if err := m.emitFunction(w, f, used); err != nil {
			return fmt.Errorf("%s: %w", decl.Name, err)
		}
	}
	return nil
}

func (m *model) signature(f *funcInfo) string {
	params := make([]string, 0, len(f.decl.Params)+1)
	if f.depth {
		params = append(params, "d int")
	}
	for _, p := range f.decl.Params {
		params = append(params, fmt.Sprintf("v%d %s", p.ID, m.goType(p.Type)))
	}
	result := m.goType(f.decl.Result)
	if f.depth {
		result = "(" + result + ", error)"
	}
	return fmt.Sprintf("%s(%s) %s", f.callName, strings.Join(params, ", "), result)
}

func (m *model) emitDepthWrapper(w *bytes.Buffer, f *funcInfo) {
	params, args := []string{}, []string{"0"}
	for _, p := range f.decl.Params {
		params = append(params, fmt.Sprintf("v%d %s", p.ID, m.goType(p.Type)))
		args = append(args, fmt.Sprintf("v%d", p.ID))
	}
	fmt.Fprintf(w, "\n// %s is the Lean function %s. It recurses; a chain of more than\n// MaxDepth nested calls returns ErrDepth instead of exhausting the stack.\nfunc %s(%s) (%s, error) {\nreturn %s(%s)\n}\n",
		f.exported, f.decl.Name, f.exported, strings.Join(params, ", "), m.goType(f.decl.Result), f.callName, strings.Join(args, ", "))
}

func (m *model) emitFold(w *bytes.Buffer, f *funcInfo) {
	step := m.funcs[f.fold.step]
	typ := m.goType(f.decl.Result)
	fmt.Fprintf(w, "\n// %s is the Lean function %s, a left fold of %s over the bytes\n// of data in order. data is only read during the call; it is neither retained\n// nor modified, and its length is not limited.\n", f.exported, f.decl.Name, f.fold.step)
	if !step.depth {
		fmt.Fprintf(w, "func %s(state %s, data []byte) %s {\nfor _, b := range data {\nstate = %s(state, b)\n}\nreturn state\n}\n", f.exported, typ, typ, step.callName)
		return
	}
	fmt.Fprintf(w, "func %s(state %s, data []byte) (%s, error) {\nfor _, b := range data {\nnext, err := %s(0, state, b)\nif err != nil {\nreturn %s, err\n}\nstate = next\n}\nreturn state, nil\n}\n", f.exported, typ, typ, step.callName, m.zero(f.decl.Result))
}

type fnEmitter struct {
	m      *model
	f      *funcInfo
	live   map[int]bool
	joins  map[int]*moduleir.Join
	jumps  map[int]int
	reach  map[int]bool
	used   map[string]bool
	labels map[int]bool
}

func (m *model) emitFunction(w *bytes.Buffer, f *funcInfo, used map[string]bool) error {
	e := &fnEmitter{m: m, f: f, live: map[int]bool{}, joins: map[int]*moduleir.Join{}, jumps: map[int]int{}, reach: map[int]bool{}, used: used}
	walkCode(f.decl.Body, func(c *moduleir.Code) {
		if c.Op == "join" {
			e.joins[c.Join.ID] = c.Join
		}
	})
	e.analyze()
	if f.root && !f.depth && f.fold == nil {
		fmt.Fprintf(w, "\n// %s is the Lean function %s.\n", f.callName, f.decl.Name)
	} else {
		fmt.Fprintf(w, "\n// %s implements the Lean function %s.\n", f.callName, f.decl.Name)
	}
	fmt.Fprintf(w, "func %s {\n", m.signature(f))
	if f.selfRec {
		fmt.Fprintf(w, "if d >= MaxDepth {\nreturn %s, ErrDepth\n}\n", m.zero(f.decl.Result))
	}
	if err := e.code(w, f.decl.Body); err != nil {
		return err
	}
	w.WriteString("}\n")
	return nil
}

// analyze finds reachable joins and live variables. Every let is pure, so a
// binding nobody reads is dropped; jumps to unreachable joins never happen.
func (e *fnEmitter) analyze() {
	for changed := true; changed; {
		changed = false
		mark := func(id int) {
			if !e.live[id] {
				e.live[id] = true
				changed = true
			}
		}
		var visit func(c *moduleir.Code)
		visit = func(c *moduleir.Code) {
			switch c.Op {
			case "let":
				if e.live[c.Bind.ID] {
					for _, id := range c.Value.Args {
						mark(id)
					}
				}
				visit(c.Next)
			case "return":
				mark(c.Var)
			case "cases":
				// A single alternative reads the scrutinee only for live fields.
				needed := len(c.Alts) > 1
				for _, p := range c.Alts[0].Params {
					needed = needed || e.live[p.ID]
				}
				if needed {
					mark(c.Var)
				}
				for _, a := range c.Alts {
					visit(a.Body)
				}
			case "join":
				if e.reach[c.Join.ID] {
					visit(c.Join.Body)
				}
				visit(c.Next)
			case "jump":
				if !e.reach[c.Target] {
					e.reach[c.Target] = true
					changed = true
				}
				for i, id := range c.Args {
					if e.live[e.joins[c.Target].Params[i].ID] {
						mark(id)
					}
				}
			}
		}
		visit(e.f.decl.Body)
	}
}

func (e *fnEmitter) fail() string {
	return fmt.Sprintf("return %s, err", e.m.zero(e.f.decl.Result))
}

func (e *fnEmitter) code(w *bytes.Buffer, c *moduleir.Code) error {
	m := e.m
	switch c.Op {
	case "return":
		if e.f.depth {
			fmt.Fprintf(w, "return v%d, nil\n", c.Var)
		} else {
			fmt.Fprintf(w, "return v%d\n", c.Var)
		}
		return nil
	case "let":
		if e.live[c.Bind.ID] {
			if err := e.let(w, c); err != nil {
				return err
			}
		}
		return e.code(w, c.Next)
	case "cases":
		return e.cases(w, c)
	case "jump":
		j := e.joins[c.Target]
		var dst, src []string
		for i, id := range c.Args {
			if e.live[j.Params[i].ID] {
				dst = append(dst, fmt.Sprintf("v%d", j.Params[i].ID))
				src = append(src, fmt.Sprintf("v%d", id))
			}
		}
		if len(dst) > 0 {
			fmt.Fprintf(w, "%s = %s\n", strings.Join(dst, ", "), strings.Join(src, ", "))
		}
		fmt.Fprintf(w, "goto j%d\n", c.Target)
		e.jumps[c.Target]++
		return nil
	case "join":
		j := c.Join
		if !e.reach[j.ID] {
			return e.code(w, c.Next)
		}
		// Parameters live in the enclosing block; the continuation runs in
		// its own block, so every goto leaves scopes and never enters one.
		for _, p := range j.Params {
			if e.live[p.ID] {
				fmt.Fprintf(w, "var v%d %s\n", p.ID, m.goType(p.Type))
			}
		}
		w.WriteString("{\n")
		if err := e.code(w, c.Next); err != nil {
			return err
		}
		fmt.Fprintf(w, "}\nj%d:\n", j.ID)
		return e.code(w, j.Body)
	}
	return fmt.Errorf("unsupported code operation %q", c.Op)
}

func (e *fnEmitter) let(w *bytes.Buffer, c *moduleir.Code) error {
	m := e.m
	dst := fmt.Sprintf("v%d", c.Bind.ID)
	args := make([]string, len(c.Value.Args))
	for i, id := range c.Value.Args {
		args[i] = fmt.Sprintf("v%d", id)
	}
	switch c.Value.Kind {
	case "uint8", "uint16", "uint32", "uint64":
		fmt.Fprintf(w, "%s := %s(%s)\n", dst, c.Value.Kind, c.Value.Name)
	case "primitive":
		statements, err := primitiveStatements(dst, c.Value.Name, args)
		if err != nil {
			return err
		}
		if primitive, _ := LookupPrimitive(c.Value.Name); primitive.Result == "Bool" && m.types["Bool"].kind != kindBool {
			return fmt.Errorf("primitive %s requires the canonical Lean Bool", c.Value.Name)
		}
		e.used[c.Value.Name] = true
		w.WriteString(statements)
	case "constructor":
		ref := m.ctors[c.Value.Name]
		fmt.Fprintf(w, "%s := %s\n", dst, m.constructorExpr(m.types[ref.typ], ref.index, args))
	case "call":
		callee := m.funcs[c.Value.Name]
		if callee.depth {
			fmt.Fprintf(w, "%s, err := %s(d+1, %s)\nif err != nil {\n%s\n}\n", dst, callee.callName, strings.Join(args, ", "), e.fail())
		} else {
			fmt.Fprintf(w, "%s := %s(%s)\n", dst, callee.callName, strings.Join(args, ", "))
		}
	default:
		return fmt.Errorf("unsupported value kind %q", c.Value.Kind)
	}
	return nil
}

func (e *fnEmitter) bind(w *bytes.Buffer, a moduleir.Alt, source string, fields []string) {
	for i, p := range a.Params {
		if e.live[p.ID] {
			fmt.Fprintf(w, "v%d := %s.%s\n", p.ID, source, fields[i])
		}
	}
}

func (e *fnEmitter) cases(w *bytes.Buffer, c *moduleir.Code) error {
	info := e.m.types[c.Type]
	v := fmt.Sprintf("v%d", c.Var)
	switch info.kind {
	case kindBool:
		var yes, no *moduleir.Code
		for _, a := range c.Alts {
			if a.Constructor == "Bool.true" {
				yes = a.Body
			} else {
				no = a.Body
			}
		}
		fmt.Fprintf(w, "if %s {\n", v)
		if err := e.code(w, yes); err != nil {
			return err
		}
		w.WriteString("}\n")
		return e.code(w, no)
	case kindRecord:
		e.bind(w, c.Alts[0], v, info.fields[0])
		return e.code(w, c.Alts[0].Body)
	}
	source := v
	if info.kind == kindBoxed {
		source = fmt.Sprintf("n%d", c.Var)
		bound := false
		for _, a := range c.Alts {
			for _, p := range a.Params {
				bound = bound || e.live[p.ID]
			}
		}
		if len(c.Alts) == 1 && !bound {
			return e.code(w, c.Alts[0].Body)
		}
		fmt.Fprintf(w, "%s := %s.node()\n", source, v)
	}
	if len(c.Alts) == 1 {
		i := e.m.ctors[c.Alts[0].Constructor].index
		e.bind(w, c.Alts[0], source, info.fields[i])
		return e.code(w, c.Alts[0].Body)
	}
	fmt.Fprintf(w, "switch %s.tag {\n", source)
	for k, a := range c.Alts {
		i := e.m.ctors[a.Constructor].index
		if k == len(c.Alts)-1 {
			// The tag is unexported and always names a constructor, so the
			// last alternative covers exactly the remaining tag.
			fmt.Fprintf(w, "default: // %s\n", a.Constructor)
		} else {
			fmt.Fprintf(w, "case %d: // %s\n", info.tags[i], a.Constructor)
		}
		e.bind(w, a, source, info.fields[i])
		if err := e.code(w, a.Body); err != nil {
			return err
		}
	}
	w.WriteString("}\n")
	return nil
}
