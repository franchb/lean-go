package nativegen

import (
	"bytes"
	"fmt"
	"strings"
)

const header = "// Code generated by lean-go (native mode); DO NOT EDIT.\n\npackage extracted\n"

func (m *model) emitFunctions(w *bytes.Buffer, used map[string]bool) error {
	w.WriteString(header)
	for _, decl := range m.program.Functions {
		f := m.funcs[decl.Name]
		if f.fold != nil {
			m.emitFold(w, f)
		}
		if f.elided {
			continue
		}
		if f.root && f.depth && f.fold == nil {
			m.emitDepthWrapper(w, f)
		}
		if err := m.emitFunction(w, f, used); err != nil {
			return fmt.Errorf("%s: %w", decl.Name, err)
		}
	}
	return nil
}

func (m *model) signature(f *funcInfo) string {
	params := make([]string, 0, len(f.decl.Params)+1)
	if f.depth {
		params = append(params, "d int")
	}
	for _, p := range f.decl.Params {
		params = append(params, fmt.Sprintf("v%d %s", p.ID, m.goType(p.Type)))
	}
	result := m.goType(f.decl.Result)
	if f.depth {
		result = "(" + result + ", error)"
	}
	return fmt.Sprintf("%s(%s) %s", f.callName, strings.Join(params, ", "), result)
}

func (m *model) emitDepthWrapper(w *bytes.Buffer, f *funcInfo) {
	params, args := []string{}, []string{"0"}
	for _, p := range f.decl.Params {
		params = append(params, fmt.Sprintf("v%d %s", p.ID, m.goType(p.Type)))
		args = append(args, fmt.Sprintf("v%d", p.ID))
	}
	fmt.Fprintf(w, "\n// %s is the Lean function %s. It recurses; a chain of more than\n// MaxDepth nested calls returns ErrDepth instead of exhausting the stack.\nfunc %s(%s) (%s, error) {\nreturn %s(%s)\n}\n",
		f.exported, f.decl.Name, f.exported, strings.Join(params, ", "), m.goType(f.decl.Result), f.callName, strings.Join(args, ", "))
}

func (m *model) emitFold(w *bytes.Buffer, f *funcInfo) {
	step := m.funcs[f.fold.step]
	typ := m.goType(f.decl.Result)
	fmt.Fprintf(w, "\n// %s is the Lean function %s, a left fold of %s over the bytes\n// of data in order. data is only read during the call; it is neither retained\n// nor modified, and its length is not limited.\n", f.exported, f.decl.Name, f.fold.step)
	if !step.depth {
		fmt.Fprintf(w, "func %s(state %s, data []byte) %s {\nfor _, b := range data {\nstate = %s(state, b)\n}\nreturn state\n}\n", f.exported, typ, typ, step.callName)
		return
	}
	fmt.Fprintf(w, "func %s(state %s, data []byte) (%s, error) {\nfor _, b := range data {\nnext, err := %s(0, state, b)\nif err != nil {\nreturn %s, err\n}\nstate = next\n}\nreturn state, nil\n}\n", f.exported, typ, typ, step.callName, m.zero(f.decl.Result))
}

