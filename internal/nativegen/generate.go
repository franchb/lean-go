// Package nativegen compiles validated module IR into plain, unmetered Go.
//
// Native mode maps Lean scalars to Go unsigned integers and Bool to bool,
// structures to Go structs, other non-recursive inductive types to value
// structs with an unexported tag, and recursive inductive types to immutable
// handles. Every value a caller can construct without unsafe or reflection is
// a valid Lean value, including every Go zero value. Generated functions are
// therefore total, except that recursive functions report ErrDepth once a
// chain of nested calls exceeds a depth fixed at generation time. See
// docs/native-mode.md.
package nativegen

import (
	"bytes"
	"crypto/sha256"
	"embed"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"go/format"
	"io/fs"
	"sort"
	"strings"

	"github.com/franchb/lean-go/internal/moduleir"
)

// Version identifies the native emitter and its output conventions.
const Version = "lean-go-nativegen/v1"

// ManifestSchema identifies the native manifest layout.
const ManifestSchema = "lean-go-native-manifest/v1"

// DefaultMaxDepth bounds nested calls along recursive call chains. At this
// depth generated frames use well under the default 1 GB goroutine stack limit.
const DefaultMaxDepth = 10000

// Options configures native generation.
type Options struct {
	// MaxDepth is the generated MaxDepth constant: the number of nested calls
	// a recursive call chain may make before it returns ErrDepth. Zero selects
	// DefaultMaxDepth; it must not exceed 1<<24.
	MaxDepth int
}

// Generate validates p and returns the native Go package files and manifest.
func Generate(p *moduleir.Program, opts Options) (map[string][]byte, error) {
	if err := moduleir.Validate(p); err != nil {
		return nil, fmt.Errorf("validate module IR: %w", err)
	}
	if opts.MaxDepth == 0 {
		opts.MaxDepth = DefaultMaxDepth
	}
	if opts.MaxDepth < 1 || opts.MaxDepth > 1<<24 {
		return nil, fmt.Errorf("native max depth %d outside 1..%d", opts.MaxDepth, 1<<24)
	}
	m, err := newModel(p, opts.MaxDepth)
	if err != nil {
		return nil, err
	}
	var doc, types, functions bytes.Buffer
	m.emitDoc(&doc)
	m.emitTypes(&types)
	used := map[string]bool{}
	if err := m.emitFunctions(&functions, used); err != nil {
		return nil, err
	}
	files := map[string][]byte{"native.go": doc.Bytes(), "types.go": types.Bytes(), "functions.go": functions.Bytes()}
	for name, data := range files {
		formatted, err := format.Source(data)
		if err != nil {
			return nil, fmt.Errorf("format %s: %w", name, err)
		}
		files[name] = formatted
	}
	manifest, err := m.manifest(files, used)
	if err != nil {
		return nil, err
	}
	files["manifest.json"] = manifest
	return files, nil
}

func (m *model) emitDoc(w *bytes.Buffer) {
	fmt.Fprintf(w, `// Code generated by lean-go (native mode); DO NOT EDIT.

// Package extracted is plain Go generated from the Lean module %s.
//
// Every value of a generated type that can be built without unsafe or
// reflection, including each zero value, is a valid Lean value. Functions are
// total, except that recursive functions return ErrDepth when a chain of
// nested calls would exceed MaxDepth.
package extracted

import "errors"

// MaxDepth is the number of nested calls a recursive call chain may make,
// fixed when this package was generated.
const MaxDepth = %d

// ErrDepth reports that a recursive call chain would exceed MaxDepth.
var ErrDepth = errors.New("lean-go: recursion depth limit exceeded")
`, strings.ReplaceAll(m.program.Module, "\n", " "), m.maxDepth)
}

//go:embed *.go
var sources embed.FS

// SourceDigest identifies the emitter's non-test Go sources.
func SourceDigest() string {
	var names []string
	fs.WalkDir(sources, ".", func(path string, d fs.DirEntry, err error) error {
		if err == nil && !d.IsDir() && !strings.HasSuffix(path, "_test.go") {
			names = append(names, path)
		}
		return nil
	})
	sort.Strings(names)
	h := sha256.New()
	for _, name := range names {
		data, _ := sources.ReadFile(name)
		fmt.Fprintf(h, "%d:%s%d:", len(name), name, len(data))
		h.Write(data)
	}
	return hex.EncodeToString(h.Sum(nil))
}

func digest(data []byte) string { sum := sha256.Sum256(data); return hex.EncodeToString(sum[:]) }

// APIType describes one generated Go type in the manifest.
type APIType struct {
	Go           string            `json:"go"`
	Kind         string            `json:"kind"`
	Zero         string            `json:"zero,omitempty"`
	Fields       []string          `json:"fields,omitempty"`
	Constructors map[string]string `json:"constructors,omitempty"`
	Is           map[string]string `json:"is,omitempty"`
	As           map[string]string `json:"as,omitempty"`
	String       string            `json:"string,omitempty"`
}

// APIFunction describes one exported root.
type APIFunction struct {
	Go       string `json:"go"`
	Error    bool   `json:"error"`
	ByteFold string `json:"byte_fold_step,omitempty"`
}

// API is the manifest's complete mapping of the public Go surface.
type API struct {
	Types     map[string]APIType     `json:"types"`
	Functions map[string]APIFunction `json:"functions"`
	Elided    []string               `json:"elided_types,omitempty"`
}

func (m *model) api() API {
	api := API{Types: map[string]APIType{}, Functions: map[string]APIFunction{}}
	for name, info := range m.types {
		if _, scalar := scalarWidths[name]; scalar || info.kind == kindBool {
			api.Types[name] = APIType{Go: info.goName, Kind: kindNames[info.kind]}
		}
	}
	for _, name := range m.order {
		info := m.types[name]
		t := APIType{Go: info.goName, Kind: kindNames[info.kind], Zero: info.decl.Constructors[info.zeroCtor].Name}
		if info.kind == kindRecord {
			t.Fields = info.fields[0]
		} else {
			t.Constructors, t.Is, t.As = map[string]string{}, map[string]string{}, map[string]string{}
			for i, c := range info.decl.Constructors {
				t.Constructors[c.Name] = info.ctorFuncs[i]
				t.Is[c.Name] = info.isMethods[i]
				if info.asMethods[i] != "" {
					t.As[c.Name] = info.asMethods[i]
				}
			}
			t.String = info.stringer
		}
		api.Types[name] = t
	}
	for _, root := range m.roots {
		f := m.funcs[root]
		entry := APIFunction{Go: f.exported, Error: f.depth}
		if f.fold != nil {
			entry.ByteFold = f.fold.step
			entry.Error = m.foldFails(f)
		}
		api.Functions[root] = entry
	}
	if m.listType != "" {
		api.Elided = []string{m.listType}
	}
	return api
}

func (m *model) manifest(files map[string][]byte, used map[string]bool) ([]byte, error) {
	canonical, err := json.Marshal(m.program)
	if err != nil {
		return nil, err
	}
	hashes := map[string]string{}
	for name, data := range files {
		hashes[name] = digest(data)
	}
	var primitives []Primitive
	for name := range used {
		primitive, _ := LookupPrimitive(name)
		primitives = append(primitives, primitive)
	}
	sort.Slice(primitives, func(i, j int) bool { return primitives[i].Name < primitives[j].Name })
	manifest := struct {
		Schema          string            `json:"schema"`
		Mode            string            `json:"mode"`
		Generator       string            `json:"generator"`
		GeneratorSource string            `json:"generator_source_sha256"`
		ValidatorSource string            `json:"validator_source_sha256"`
		IR              string            `json:"ir_sha256"`
		MaxDepth        int               `json:"max_depth"`
		Program         *moduleir.Program `json:"program"`
		Files           map[string]string `json:"generated_files"`
		Evidence        string            `json:"evidence"`
		Primitives      []Primitive       `json:"primitives"`
		GoAPI           API               `json:"go_api"`
	}{ManifestSchema, "native", Version, SourceDigest(), moduleir.SourceDigest(), digest(canonical), m.maxDepth, m.program, hashes,
		"Tested/trusted extraction; not an end-to-end proof of Go correctness. Native mode enforces no resource budgets other than MaxDepth.",
		primitives, m.api()}
	if manifest.Primitives == nil {
		manifest.Primitives = []Primitive{}
	}
	data, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}
